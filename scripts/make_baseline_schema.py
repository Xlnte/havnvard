#!/usr/bin/env python3
"""Build schema/baseline.sql: the one-file database install for a NEW HavnVard site (INFRA-557).

The files in migrations/ are the change history of the original deployment. They name that site's hosts and
read a table from another system, so they cannot build the schema on an empty database. The baseline is the
CURRENT schema, taken from a working database with pg_dump, made generic, plus schema/seed.sql.

Maintainer use (after a schema change has been applied to a working database):

    pg_dump "$POSTGRES_URL" --schema-only --no-owner --no-privileges -n diskaudit -f /tmp/diskaudit.sql
    python3 scripts/make_baseline_schema.py /tmp/diskaudit.sql -o schema/baseline.sql

    (add  --site-names <your private rules file>  so your own host and person names are rewritten and forbidden)

The script refuses (exit 1) if any forbidden name survives, so a private name cannot be published by accident.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
SEED = HERE / "schema" / "seed.sql"

# Views that only make sense for one named host and that no HavnVard code reads.
DROP_OBJECTS = {"v_nas_orphans"}

# Generic comment rewrites, applied in order before the site rules: sentences that only describe one
# deployment's data, and runbook paths.
COMMENT_REWRITES = [
    (r",? confirmed live 20\d\d-\d\d-\d\d", ""),
    (r" Plane INFRA-\d+\.", ""),
    (r" -- current critical_patterns seeding matches .*?not a bug\.",
     " -- can be a very large set when broad critical_patterns are seeded."),
    (r" As of 20\d\d-\d\d-\d\d: .*?point-in-time report\.",
     " Coverage fills in as NAS crawl and dedup work lands; this is a live view, not a point-in-time report."),
    (r"/home/[A-Za-z0-9_.-]+/runbooks/[^\s']*", "the project runbook"),
    (r"thoth\.census", "an external system registry"),
]

# Generic patterns that must not appear anywhere in the output (matched case-insensitively). Your own host,
# person and share names go in a PRIVATE --site-names file, so this public script never spells them out.
FORBIDDEN = [r"/home/[a-z]", r"thoth\.", r"CACHEDEV1_DATA/(?!homes)", r"\bplane\b", r"INFRA-\d+", r"As of 20\d\d-"]

Rule = tuple[str, "str | None"]   # (regex, replacement in comments; None = forbid only)


def read_site_rules(path: str) -> list[Rule]:
    """One rule per line: `regex => replacement` rewrites it inside COMMENTs (and forbids it everywhere);
    a bare `regex` only forbids it. Blank lines and lines starting with # are ignored."""
    rules: list[Rule] = []
    for raw in Path(path).read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if "=>" in line:
            pat, rep = (x.strip() for x in line.split("=>", 1))
            rules.append((pat, rep))
        else:
            rules.append((line, None))
    return rules


HEADER = """\
-- HavnVard database schema: baseline for a NEW install (generated by scripts/make_baseline_schema.py).
-- Apply once to an empty PostgreSQL 15+ database:   psql "$POSTGRES_URL" -v ON_ERROR_STOP=1 -f schema/baseline.sql
-- Do NOT apply it to a database that already has the diskaudit schema; migrations/ is the history of the
-- original deployment and is not needed for a new install.
"""


def split_blocks(text: str) -> list[str]:
    """pg_dump writes one '--\\n-- Name: ...' header per object; split so whole objects can be dropped."""
    parts = re.split(r"(?m)^(?=--\n-- (?:Name|Data for Name): )", text)
    return parts


def block_name(block: str) -> str:
    m = re.search(r"^-- (?:Name|Data for Name): ([^;]+);", block, re.M)
    return m.group(1).strip() if m else ""


def build(dump: str, site_rules: list[Rule]) -> str:
    out = []
    for block in split_blocks(dump):
        name = block_name(block)
        last_word = name.split()[-1] if name else ""
        if last_word in DROP_OBJECTS:
            continue
        out.append(block)
    text = "".join(out)

    # psql-only meta commands (pg_dump 16.10+ \restrict) and version banners.
    text = re.sub(r"(?m)^\\(?:un)?restrict .*\n", "", text)
    text = re.sub(r"(?m)^-- Dumped (?:from|by) .*\n", "", text)

    # A host column must be given by the writer; no site gets a silent default host.
    text = re.sub(r"host text DEFAULT '[^']*'::text NOT NULL", "host text NOT NULL", text)

    def fix_comment(m: re.Match) -> str:
        s = m.group(0)
        for pat, rep in COMMENT_REWRITES:
            s = re.sub(pat, rep, s)
        for pat, rep in site_rules:
            if rep is not None:
                s = re.sub(pat, rep, s)
        return s

    text = re.sub(r"(?ms)^COMMENT ON .*?';\n", fix_comment, text)
    text = text.rstrip() + "\n\n" + SEED.read_text(encoding="utf-8")
    # pg_dump --schema-only creates materialized views WITH NO DATA; reading one then errors
    # "has not been populated". Populate each after the seed so a new install's pages work at once.
    mvs = re.findall(r"(?m)^CREATE MATERIALIZED VIEW (diskaudit\.\w+) AS", text)
    if mvs:
        text += "\n-- Populate the materialized views (created empty by the schema dump).\n"
        text += "".join(f"REFRESH MATERIALIZED VIEW {mv};\n" for mv in mvs)
    return HEADER + text


def leaks(text: str, site_rules: list[Rule]) -> list[str]:
    found = []
    pats = FORBIDDEN + [p for p, _ in site_rules]
    for i, line in enumerate(text.splitlines(), 1):
        for pat in pats:
            if re.search(pat, line, re.I):
                found.append(f"{i}: {pat}: {line[:120]}")
    return found


def main() -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    ap.add_argument("dump", help="pg_dump --schema-only -n diskaudit output")
    ap.add_argument("-o", "--output", help="write here, only after the checks pass; default stdout. Use this, not '>', so a "
                    "refusal never leaves an empty baseline")
    ap.add_argument("--site-names", help="PRIVATE rules file (never commit it): `regex => replacement` per line "
                    "to rewrite your host/person/share names in comments, or a bare `regex` to forbid it")
    a = ap.parse_args()
    rules = read_site_rules(a.site_names) if a.site_names else []
    text = build(Path(a.dump).read_text(encoding="utf-8"), rules)
    bad = leaks(text, rules)
    if bad:
        print("refusing: site names left in the baseline:\n  " + "\n  ".join(bad[:30]), file=sys.stderr)
        return 1
    if a.output:
        # Opened only after the leak check passed, so a refusal leaves the old file untouched.
        Path(a.output).write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
