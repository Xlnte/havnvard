-- WHY THIS MIGRATION EXISTS (the design flaw being fixed):
-- diskaudit.v_backup_coverage (20260718_diskaudit_backup_coverage_v2.sql) only covers
-- files matching diskaudit.critical_patterns (~46% of the table). crosshost_verify.py's
-- candidate set (20260725_diskaudit_crosshost_integrity_v1.sql) only covers files whose
-- SIZE appears on >=2 hosts and is >=1MB. BOTH are structurally wrong for "what needs
-- backing up" -- a file that most needs a backup check is exactly one that exists
-- NOWHERE else, so it can never enter either candidate set. Measured live 2026-07-25:
-- server-1 5,784,880 live files -> only 16,452 ever evaluated by crosshost_verify (0.3%);
-- agent-1 331,934 live files -> only 425 evaluated (0.1%).
--
-- This migration adds a THIRD, complete-universe path: every in-scope server/agent-1 file
-- gets exactly one row in diskaudit.backup_coverage. Additive only -- does not touch
-- v_backup_coverage, v_critical_files, v_nas_orphans, or crosshost_verify's tables/columns.

BEGIN;

-- 1. Scope-exclusion rules -- auditable, the operator-editable, NOT hardcoded in Python.
--    Evaluated in `priority` order (ascending); first matching active rule wins.
--    A file matching no active rule is IN_SCOPE (must be classified as backed-up/not).
CREATE TABLE IF NOT EXISTS diskaudit.backup_scope_rules (
    rule_id       bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    host_pattern  text NOT NULL,   -- SQL LIKE pattern against files.host ('%' = any host)
    path_pattern  text NOT NULL,   -- SQL LIKE pattern against files.path
    category      text NOT NULL CHECK (category IN (
                      'excluded_os', 'excluded_cache', 'excluded_transient',
                      'excluded_own_backup_staging', 'excluded_other'
                  )),
    reason        text NOT NULL,
    priority      integer NOT NULL DEFAULT 100,
    active        boolean NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE diskaudit.backup_scope_rules IS
  'Auditable, editable exclusion rules for backup-coverage scoping. A file is EXCLUDED '
  'from the "needs backup" universe iff it matches an active rule here, with the exact '
  'rule + reason recorded on the resulting diskaudit.backup_coverage row -- so the operator can '
  'see and challenge every exclusion, not just trust a hardcoded list. Edit via SQL '
  '(INSERT/UPDATE active=false), never by editing backup_coverage.py''s source.';

