-- 2. Complete-universe backup coverage table. One row per (host, path) for every
--    IN-SCOPE server/agent-1 file (nas-1 itself is never a row here -- it's the
--    destination being checked against, not something needing "backup coverage").
--    EXCLUDED rows ARE still recorded (with rule_id + reason) so exclusions are visible
--    and auditable, not silently dropped from the picture.
CREATE TABLE IF NOT EXISTS diskaudit.backup_coverage (
    host                   text NOT NULL,
    path                   text NOT NULL,
    size_bytes             bigint,
    inode                  bigint,
    nlink                  integer,
    classification         text NOT NULL CHECK (classification IN (
                              'BACKED_UP_VERIFIED', 'BACKED_UP_UNVERIFIED',
                              'NOT_BACKED_UP', 'EXCLUDED'
                           )),
    match_method           text CHECK (match_method IN (
                              'hash_proven', 'path_size_mtime',
                              'restic_snapshot_listing', 'none'
                           )),
    excluded_rule_id       bigint REFERENCES diskaudit.backup_scope_rules(rule_id),
    matched_nas_host       text,
    matched_nas_path       text,
    matched_restic_target  text,
    checked_at             timestamptz NOT NULL DEFAULT now(),
    run_id                 bigint,
    notes                  text,
    PRIMARY KEY (host, path)
);

COMMENT ON TABLE diskaudit.backup_coverage IS
  'Complete-universe answer to "what on server/agent-1 is NOT safely on the NAS" -- one '
  'row per in-scope file (EXCLUDED rows included, for auditability). Built by '
  'backup_coverage.py, NOT limited to critical_patterns (see v_backup_coverage) or the '
  'cross-host size-candidate set (see crosshost_verify.py) -- both of those cover <1% of '
  'the true file universe on server-1/agent-1, confirmed live 2026-07-25. '
  'BACKED_UP_VERIFIED = hash-proven bit-identical copy confirmed. '
  'BACKED_UP_UNVERIFIED = a plausible NAS/restic counterpart exists by path+size+mtime '
  'but has not (yet) been cryptographically confirmed -- never report this tier as proof. '
  'NOT_BACKED_UP = no counterpart found at all -- the actual deliverable list. '
  'EXCLUDED = matched a diskaudit.backup_scope_rules rule (see excluded_rule_id).';

CREATE INDEX IF NOT EXISTS idx_backup_coverage_classification
    ON diskaudit.backup_coverage (host, classification);
CREATE INDEX IF NOT EXISTS idx_backup_coverage_size
    ON diskaudit.backup_coverage (classification, size_bytes DESC);
CREATE INDEX IF NOT EXISTS idx_backup_coverage_inode
    ON diskaudit.backup_coverage (host, inode);

-- 3. Run-tracking table for backup_coverage.py, same shape as scan_runs/dedup_runs/
--    crosshost_verify_runs -- gives classify/verify runs a heartbeat home so monitor.py
--    (once wired -- see runbook known-gap note, same gap crosshost_verify_runs has today)
--    and a human can tell "still running" from "stuck."
CREATE TABLE IF NOT EXISTS diskaudit.backup_coverage_runs (
    run_id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    phase               text NOT NULL CHECK (phase IN ('classify', 'verify')),
    host                text,
    started_at          timestamptz NOT NULL DEFAULT now(),
    finished_at         timestamptz,
    status              text NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'completed', 'failed')),
    files_considered    bigint,
    files_excluded      bigint,
    files_matched       bigint,
    files_verified      bigint,
    files_not_backed_up bigint,
    last_heartbeat_at   timestamptz,
    current_stage       text,
    notes               text
);

-- 4. Widen run_heartbeats.run_type + heartbeat.py's table_map (see heartbeat.py edit,
--    same PR) so backup_coverage.py's classify/verify runs get heartbeat rows too.
ALTER TABLE diskaudit.run_heartbeats DROP CONSTRAINT IF EXISTS run_heartbeats_run_type_check;
ALTER TABLE diskaudit.run_heartbeats ADD CONSTRAINT run_heartbeats_run_type_check
    CHECK (run_type = ANY (ARRAY['scan'::text, 'dedup'::text, 'restic_backup'::text,
                                  'crosshost_verify'::text, 'backup_coverage'::text]));

